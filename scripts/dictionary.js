/** Баровии: родительный, дательный и предложный совпадают - разводим по предлогу. */
function barovii(m, off, str) {
  const prev = str.slice(Math.max(0, off - 40), off).replace(/[«»"(]/g, " ").trim().split(/\s+/).pop()?.toLowerCase() ?? "";
  if (/^(в|во|на|о|об|при)$/.test(prev)) return NACHT.prep;
  if (/^(к|ко|по)$/.test(prev)) return NACHT.dat;
  return NACHT.gen;
}

